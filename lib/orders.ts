import "server-only";

import { createHash } from "node:crypto";
import { cache } from "react";
import { ORDER_SELECT, toFeedback, toOrder, toPrivateSettings } from "./mappers";
import { createAdminClient } from "./supabase/admin";
import { hasSupabaseConfig } from "./supabase/env";
import type { Feedback, Order, PrivateSettings } from "./types";

/**
 * Order reads that need to bypass row level security.
 *
 * `orders` has no policy for anonymous visitors at all, which is what keeps a
 * leaked anon key from exposing customer names, phone numbers and addresses. The
 * two places the public still needs to see an order, the tokenised status page,
 * and the emails, go through the service role here instead, server-side only,
 * and narrow what they return.
 */

/**
 * One order, by its unguessable token. This is the only public read of an order
 * and it is a bearer credential: whoever has the link can see the order.
 */
export async function getOrderByToken(token: string): Promise<Order | null> {
	// 32 hex characters, generated by gen_random_bytes(16) in place_order.
	if (!/^[0-9a-f]{32}$/.test(token)) return null;
	if (!hasSupabaseConfig()) return null;

	const supabase = createAdminClient();
	const { data, error } = await supabase
		.from("orders")
		.select(ORDER_SELECT)
		.eq("token", token)
		.maybeSingle();

	if (error || !data) return null;
	return toOrder(data);
}

/**
 * What this customer already said, if they have said anything.
 *
 * `feedback` has no anon policy either, so this goes through the service role
 * for the same reason the read above does. It is only ever asked on the
 * feedback page, after the token has already been matched to an order, and it
 * is what lets that page show someone their own words back rather than an empty
 * form they have already filled in once.
 */
export async function feedbackForOrder(orderId: string): Promise<Feedback | null> {
	if (!hasSupabaseConfig()) return null;

	const supabase = createAdminClient();
	const { data, error } = await supabase
		.from("feedback")
		.select("*")
		.eq("order_id", orderId)
		.maybeSingle();

	if (error || !data) return null;
	return toFeedback(data);
}

/**
 * The stars somebody already gave, keyed by product id, so a second visit to
 * the feedback link shows what they said rather than an empty row of stars.
 *
 * Through the service role like its sibling above: the ratings table has no
 * read policy for anon, and the token in the URL is what authorises this.
 *
 * An empty object covers both "they rated nothing" and "the read failed". The
 * page treats them the same, which is right: the worst either can do is show
 * an unrated row that they then rate again.
 */
export async function ratingsForFeedback(feedbackId: string): Promise<Record<string, number>> {
	if (!hasSupabaseConfig()) return {};

	const supabase = createAdminClient();
	const { data, error } = await supabase
		.from("feedback_ratings")
		.select("product_id, rating")
		.eq("feedback_id", feedbackId);

	if (error) {
		console.error("[vvbakes] could not read the existing ratings", error);
		return {};
	}

	return Object.fromEntries((data ?? []).map((row) => [row.product_id, row.rating]));
}

/**
 * The private half of settings. Never pass this to a client component whole.
 *
 * Cached per request to match its sibling `getSettings`: several actions read
 * both side by side, and nothing writes these settings and then reads them back
 * in the same request.
 */
export const getPrivateSettings = cache(async (): Promise<PrivateSettings> => {
	const empty: PrivateSettings = {
		bankAccountName: null,
		bankAccountNumber: null,
		pickupAddress: null,
		notificationEmail: null,
	};

	if (!hasSupabaseConfig()) return empty;

	const supabase = createAdminClient();
	const { data, error } = await supabase
		.from("site_settings_private")
		.select("*")
		.eq("id", 1)
		.maybeSingle();

	if (error || !data) return empty;
	return toPrivateSettings(data);
});

/**
 * A salted, truncated hash of the caller's address.
 *
 * Enough to notice one machine submitting five orders in a minute; not enough to
 * identify anyone or to be useful if the database leaks. The salt is the service
 * role key, which is already the most sensitive value the server holds, so this
 * adds no new secret to manage.
 */
export function hashIp(ip: string | null): string | null {
	if (!ip) return null;
	const salt = process.env.SUPABASE_SERVICE_ROLE_KEY ?? "vvbakes";
	return createHash("sha256").update(`${salt}:${ip}`).digest("hex").slice(0, 32);
}

/** The client address, as far as the proxy in front of us reports it. */
export function clientIp(headers: Headers): string | null {
	const forwarded = headers.get("x-forwarded-for");
	if (forwarded) {
		const first = forwarded.split(",")[0]?.trim();
		if (first) return first;
	}
	return headers.get("x-real-ip");
}
